class MultiColorResolutionTest(TestCase):
    def test_single_color_exact_match(self):
        mappings = {"black": "Black", "red": "Red"}
        colors, primary, warnings = resolve_system_colors("Black", mappings)
        self.assertEqual(colors, ["Black"])
        self.assertEqual(primary, "Black")
        self.assertEqual(warnings, [])

    def test_compound_ampersand(self):
        mappings = {"red": "Red", "black": "Black"}
        colors, primary, warnings = resolve_system_colors("Red & Black", mappings)
        self.assertEqual(colors, ["Red", "Black"])
        self.assertEqual(primary, "Red")
        self.assertEqual(warnings, [])

    def test_compound_slash(self):
        mappings = {"pink": "Pink", "purple": "Purple"}
        colors, primary, warnings = resolve_system_colors("Pink / Purple", mappings)
        self.assertEqual(colors, ["Pink", "Purple"])
        self.assertEqual(primary, "Pink")

    def test_compound_partial_resolve(self):
        mappings = {"red": "Red"}
        colors, primary, warnings = resolve_system_colors("Red & Coral", mappings)
        self.assertEqual(colors, ["Red"])
        self.assertEqual(primary, "Red")
        self.assertTrue(any("Coral" in w.get("detail", "") for w in warnings))

    def test_full_match_overrides_split(self):
        mappings = {"red & black": "MultiRedBlack", "red": "Red", "black": "Black"}
        colors, primary, _ = resolve_system_colors("Red & Black", mappings)
        self.assertEqual(colors, ["MultiRedBlack"])
        self.assertEqual(primary, "MultiRedBlack")

    def test_deduplication(self):
        mappings = {"black": "Black"}
        colors, primary, _ = resolve_system_colors("Black & Black", mappings)
        self.assertEqual(colors, ["Black"])

    def test_empty_input(self):
        colors, primary, warnings = resolve_system_colors("", {})
        self.assertEqual(colors, [])
        self.assertEqual(primary, "")
        self.assertEqual(warnings, [])


class FullNormalizationTest(TestCase):
    def test_full_pipeline(self):
        result = normalize_product(
            name="Nimbus9 Nimbus9 Alto 2 Case for iPhone 15 Pro - Clear",
            brand="Nimbus9",
            category="Cases",
            color="Clear",
            short_description=None,
            description="Great case. Claims available at nimbus9usa.com",
        )
        self.assertIn("name", result.changes)
        self.assertEqual(result.changes["name"].count("Nimbus9"), 1)
        self.assertIsNone(result.changes["short_description"])
        self.assertNotIn("CIXCI", result.changes.get("meta_title", ""))
        self.assertNotIn("CIXCI", result.changes.get("meta_description", ""))
        self.assertNotIn("nimbus9usa.com", result.changes.get("description", "") or "")

    def test_short_desc_never_generated(self):
        result = normalize_product(
            name="Test Product",
            brand="Brand",
            short_description=None,
        )
        self.assertIsNone(result.changes["short_description"])

    def test_pass_outcome(self):
        result = normalize_product(
            name="OtterBox Defender Case",
            brand="OtterBox",
            category="Cases",
        )
        self.assertEqual(result.outcome, Outcome.PASS)
        self.assertEqual(result.rule_version, "1.0.0")


class VendorColorMappingAPITest(TestCase):
    """Tests for VendorColorMapping API endpoints."""

    def setUp(self):
        from apps.catalog.models import VendorColorMapping
        import uuid
        self.vendor_id = uuid.UUID("6360b2ba-7606-4946-8f51-3ea3975a7d20")
        VendorColorMapping.objects.filter(vendor_company_reference=self.vendor_id).delete()

    def test_create_mapping(self):
        from apps.catalog.models import VendorColorMapping
        mapping = VendorColorMapping.objects.create(
            vendor_company_reference=self.vendor_id,
            vendor_color="Mint",
            system_color="Green",
            status="active",
        )
        self.assertEqual(mapping.system_color, "Green")
        self.assertEqual(str(mapping), "VendorColorMapping(Mint → Green)")

    def test_unique_vendor_color_per_vendor(self):
        from apps.catalog.models import VendorColorMapping
        from django.db import IntegrityError, transaction
        VendorColorMapping.objects.create(
            vendor_company_reference=self.vendor_id,
            vendor_color="Mint",
            system_color="Green",
        )
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                VendorColorMapping.objects.create(
                    vendor_company_reference=self.vendor_id,
                    vendor_color="Mint",
                    system_color="Teal",
                )

    def test_different_vendors_same_color(self):
        import uuid
        from apps.catalog.models import VendorColorMapping
        VendorColorMapping.objects.create(
            vendor_company_reference=self.vendor_id,
            vendor_color="Mint",
            system_color="Green",
        )
        other_vendor = uuid.uuid4()
        mapping2 = VendorColorMapping.objects.create(
            vendor_company_reference=other_vendor,
            vendor_color="Mint",
            system_color="Teal",
        )
        self.assertEqual(mapping2.system_color, "Teal")

    def test_status_choices(self):
        from apps.catalog.models import VendorColorMappingStatus
        self.assertEqual(VendorColorMappingStatus.ACTIVE, "active")
        self.assertEqual(VendorColorMappingStatus.INACTIVE, "inactive")
        self.assertEqual(VendorColorMappingStatus.REVIEW_REQUIRED, "review_required")

    def tearDown(self):
        from apps.catalog.models import VendorColorMapping
        VendorColorMapping.objects.filter(vendor_company_reference=self.vendor_id).delete()


class BuyerExportFormattingTest(TestCase):
    """§14: Buyer API/Export Description Formatting."""

    def test_paragraph_plus_bullets_html(self):
        desc = "Great protective case for daily use.\n\nKey Features\n• Drop tested to 10ft\n• Slim profile design\n• Wireless charging compatible"
        result = format_description_html(desc)
        self.assertIn("<p>", result)
        self.assertIn("<ul>", result)
        self.assertIn("<li>Drop tested to 10ft</li>", result)
        self.assertNotIn("•", result)

    def test_paragraph_only_html(self):
        desc = "A simple protective case with military-grade drop protection."
        result = format_description_html(desc)
        self.assertIn("<p>", result)
        self.assertNotIn("<ul>", result)

    def test_bullets_only_html(self):
        desc = "• Drop tested to 10ft\n• Slim profile\n• Wireless charging"
        result = format_description_html(desc)
        self.assertIn("<ul>", result)
        self.assertIn("<li>", result)

    def test_plaintext_preserves_structure(self):
        desc = "Great case for daily use.\n\nKey Features\n• Drop tested to 10ft\n• Slim profile"
        result = format_description_plaintext(desc)
        self.assertIn("Key Features", result)
        self.assertIn("• Drop tested to 10ft", result)
        self.assertIn("• Slim profile", result)

    def test_plaintext_paragraph_only(self):
        desc = "A simple protective case."
        result = format_description_plaintext(desc)
        self.assertEqual(result, desc)

    def test_empty_description(self):
        self.assertEqual(format_description_html(""), "")
        self.assertEqual(format_description_plaintext(""), "")

    def test_html_escapes_special_chars(self):
        desc = "AT&T compatible case.\n\nKey Features\n• Works with <all> devices"
        result = format_description_html(desc)
        self.assertIn("AT&amp;T", result)
        self.assertIn("&lt;all&gt;", result)


class BuyerSyncDetectionTest(TestCase):
    """§15: Synchronization to Buyers — change detection."""

    def test_name_change_triggers_sync(self):
        original = {"name": "Old Name", "description": "Same"}
        proposed = {"name": "New Name", "description": "Same"}
        self.assertTrue(detect_buyer_sync_needed(original, proposed))

    def test_no_change_no_sync(self):
        vals = {"name": "Same", "description": "Same", "meta_title": "Same"}
        self.assertFalse(detect_buyer_sync_needed(vals, vals))

    def test_description_change_triggers_sync(self):
        original = {"description": "Old desc"}
        proposed = {"description": "New desc"}
        self.assertTrue(detect_buyer_sync_needed(original, proposed))

    def test_whitespace_only_change_no_sync(self):
        original = {"name": "  Same  "}
        proposed = {"name": "Same"}
        self.assertFalse(detect_buyer_sync_needed(original, proposed))

    def test_none_vs_empty_no_sync(self):
        original = {"name": None}
        proposed = {"name": ""}
        self.assertFalse(detect_buyer_sync_needed(original, proposed))

    def test_meta_title_change_triggers_sync(self):
        original = {"meta_title": "Old Title"}
        proposed = {"meta_title": "New Title"}
        self.assertTrue(detect_buyer_sync_needed(original, proposed))


