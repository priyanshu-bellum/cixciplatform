class CleanTextTest(TestCase):
    def test_transport_artifacts(self):
        self.assertEqual(clean_text("hello_x000D_world"), "hello\nworld")

    def test_html_entities(self):
        self.assertEqual(clean_text("AT&amp;T case"), "AT&T case")

    def test_repeated_spaces(self):
        self.assertEqual(clean_text("hello   world"), "hello world")

    def test_emoji_removed(self):
        result = clean_text("Great product! 🎉🔥")
        self.assertNotIn("🎉", result)
        self.assertNotIn("🔥", result)

    def test_preserves_trademark(self):
        self.assertIn("®", clean_text("Product® name"))
        self.assertIn("™", clean_text("Brand™ item"))

    def test_none_passthrough(self):
        self.assertIsNone(clean_text(None))

    def test_empty_passthrough(self):
        self.assertEqual(clean_text(""), "")


class NormalizeNameTest(TestCase):
    def test_basic_whitespace(self):
        name, codes = normalize_name("  Nimbus9  Alto  2  Case  ")
        self.assertEqual(name, "Nimbus9 Alto 2 Case")

    def test_duplicate_brand_removed(self):
        name, codes = normalize_name("Nimbus9 Nimbus9 Alto 2 Case", "Nimbus9")
        self.assertEqual(name, "Nimbus9 Alto 2 Case")
        self.assertIn("BRAND_NAME_NORMALIZED", codes)

    def test_legal_suffix_removed(self):
        name, codes = normalize_name("Nimbus9 LLC Alto 2 Case", "Nimbus9")
        self.assertNotIn("LLC", name)

    def test_empty_name_fails(self):
        name, codes = normalize_name("")
        self.assertEqual(name, "")
        self.assertTrue(any(c.get("code") == "FAIL" for c in codes))

    def test_dash_normalization(self):
        name, _ = normalize_name("Case — for — iPhone")
        self.assertIn("-", name)
        self.assertNotIn("—", name)

    def test_preserves_model_identifiers(self):
        name, _ = normalize_name("OtterBox Defender for iPhone 15 Pro Max - Black")
        self.assertIn("iPhone 15 Pro Max", name)
        self.assertIn("Black", name)


