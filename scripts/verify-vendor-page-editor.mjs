// Real local QA connection writes; no supplier request or commercial approval.
export async function verifyVendorPageEditor({call,evaluate,wait,click,fill,select,report,apiUrl,tokens,output,writeFile,path,onCreated}) {
  await click('Add API Connection')
  await select('API setup preset','generic')
  await wait('[...document.querySelectorAll("button")].some(button=>button.textContent==="Use Preset"&&!button.disabled)')
  await click('Use Preset')
  await wait('document.body.innerText.includes("Generic REST/JSON mapping template loaded")')
  const generic = await evaluate('[...document.querySelectorAll("input")].find(input=>input.closest(".MuiFormControl-root")?.innerText.includes("Items array path"))?.value')
  report.checks.push({name:'New supplier starts with Generic REST/JSON rather than Balaji-specific paths',pass:generic==='items'})
  const connectionLabel='QA generic page editor '+Date.now()
  await fill('Connection label',connectionLabel)
  await fill('Catalog HTTPS URL','https://supplier.example/catalog')
  await select('Authentication','none')
  await fill('Items array path','payload.records')
  await fill('Path for name','title')
  await fill('Path for vendor_wholesale_price_amount','pricing.wholesale')
  await select('Pagination method','page')
  await fill('Has more response path','paging.more')
  await click('Advanced JSON','button,[role=button]')
  const getJSON = () => evaluate('[...document.querySelectorAll("textarea")].find(input=>input.closest(".MuiFormControl-root")?.innerText.includes("Catalog field and pagination mapping (JSON)"))?.value')
  const configuration=JSON.parse(await getJSON())
  report.checks.push({name:'Visual mapping and pagination edits update the same JSON configuration',pass:configuration.items_path==='payload.records'&&configuration.fields.name.path==='title'&&configuration.fields.vendor_wholesale_price_amount.path==='pricing.wholesale'&&configuration.pagination==='page'&&configuration.has_more_path==='paging.more'})
  configuration.fields.name.path='display_name'
  await fill('Catalog field and pagination mapping (JSON)',JSON.stringify(configuration))
  await wait('[...document.querySelectorAll("input")].some(input=>input.closest(".MuiFormControl-root")?.innerText.includes("Path for name")&&input.value==="display_name")')
  report.checks.push({name:'Advanced JSON updates the visual field editor',pass:true})
  await fill('Catalog field and pagination mapping (JSON)',JSON.stringify({fields:{name:null}}))
  await wait('document.body.innerText.includes("mapping JSON is invalid")')
  report.checks.push({name:'Malformed mapping structure produces guidance without crashing the page',pass:await evaluate('document.body.innerText.includes("Vendor Integrations")')})
  await fill('Catalog field and pagination mapping (JSON)',JSON.stringify(configuration))
  await evaluate('[...document.querySelectorAll("label")].find(label=>label.textContent.includes("Weekly full resync")).querySelector("input").click()')
  await click('Save Catalog Connection')
  await wait('document.body.innerText.includes("Catalog connection saved.")')
  const rows=await(await fetch(apiUrl+'/integration/vendor-catalog-connections/?paginate=false',{headers:{Authorization:'Bearer '+tokens.access}})).json()
  const saved=rows.find(row=>row.label===connectionLabel)
  if(saved)onCreated(saved.id)
  report.checks.push({name:'Generic supplier configuration persists through the real API with weekly polling off',pass:!!saved&&saved.config.fields.name.path==='display_name'&&saved.config.items_path==='payload.records'&&saved.auth_type==='none'&&saved.schedule_enabled===false})
  await call('Emulation.setDeviceMetricsOverride',{width:390,height:1000,deviceScaleFactor:1,mobile:false})
  await wait('window.innerWidth===390')
  report.checks.push({name:'Dedicated Vendor page fits a narrow viewport while mapping tables scroll internally',pass:await evaluate('document.documentElement.scrollWidth<=window.innerWidth+2')})
  let screenshot=await call('Page.captureScreenshot',{format:'png'});await writeFile(path.join(output,'vendor-page-mobile.png'),Buffer.from(screenshot.data,'base64'))
  await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false})
  screenshot=await call('Page.captureScreenshot',{format:'png'});await writeFile(path.join(output,'vendor-page-generic-mapping.png'),Buffer.from(screenshot.data,'base64'))
  if(saved){
    const retirement=await fetch(apiUrl+'/integration/vendor-catalog-connections/'+saved.id+'/',{
      method:'PATCH',headers:{Authorization:'Bearer '+tokens.access,'Content-Type':'application/json','If-Match':saved.config_version},
      body:JSON.stringify({is_retired:true,schedule_enabled:false})})
    if(!retirement.ok)throw new Error('QA connection retirement failed')
    await click('Add API Connection')
    const openConnections=()=>evaluate(`(()=>{const select=[...document.querySelectorAll('[role=combobox]')].find(element=>element.closest('.MuiFormControl-root')?.innerText.includes('Saved API connection'));select.dispatchEvent(new MouseEvent('mousedown',{bubbles:true,button:0}))})()`)
    await openConnections()
    await wait('!!document.querySelector("[role=listbox]")')
    await wait(`!document.querySelector('[role=option][data-value="${saved.id}"]')`)
    report.checks.push({name:'Retired QA connections leave the default active connection list',pass:true})
    await call('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
    await call('Input.dispatchKeyEvent',{type:'keyUp',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
    await wait('!document.querySelector("[role=listbox]")')
    await evaluate('[...document.querySelectorAll("label")].find(label=>label.textContent.includes("Show retired")).querySelector("input").click()')
    await openConnections()
    await wait(`!!document.querySelector('[role=option][data-value="${saved.id}"]')`)
    report.checks.push({name:'Show retired explicitly restores access to retained connection history',pass:await evaluate(`document.querySelector('[role=option][data-value="${saved.id}"]').textContent.includes('(retired)')`)})
    await call('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
    await call('Input.dispatchKeyEvent',{type:'keyUp',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
  }
  report.checks.push({name:'Generic page editor has no uncaught UI exceptions',pass:report.consoleErrors.length===0})
  report.proof={qaConnectionId:saved?.id,remoteReads:0,existingBusinessRecordsUntouched:true}
}
